def bag_grain(share_pcts=(5, 10, 20)):
    """Если часть экспорта зерна по железной дороге уйдёт в крытые вагоны в мешках: погрузок в месяц и доля от погрузок
    зерновозов. База — экспорт зерна по РЖД январь–сентябрь 2026 г. 18,8 млн т (9 месяцев)."""
    exp_m = 18.8e6 / 9
    hop_loads = 25.9e6 / 9 / CAP["hopper"][0]
    return [(s, exp_m * s / 100 / CAP["covered_bag"][0], exp_m * s / 100 / CAP["covered_bag"][0] / hop_loads * 100)
            for s in share_pcts]


