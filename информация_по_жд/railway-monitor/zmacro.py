    teu25 = teu26[0] / (1 + teu26[1] / 100)  # 3 921 / 1,037
    g25 = g["teu"] / g["x"]                  # 362,9 / 2,4
    plat26, plat25 = teu26[0] - g["teu"], teu25 - g25
    return {"share26": g["teu"] / teu26[0] * 100, "share25": g25 / teu25 * 100, "teu25": teu25, "g25": g25,
            "plat_growth": (plat26 / plat25 - 1) * 100, "total_growth": teu26[1],
            "extra_wagons_month": (g["wagons"] - g["wagons"] / g["x"]) / 6}


