def now(w):
    """Что сейчас по данным рынка (база наблюдений): темп ставки, рабочий парк за месяц, парк к году."""
    try:
        import zrates
        S = zrates.series()
    except Exception:  # noqa: BLE001 — нет базы наблюдений
        return {}
    import zobs
    out = {}
    r = S.get(RATE_ITEM.get(w, ""), {})
    if len(r) >= 3:
        ms = sorted(r)
        ch = [(r[b] / r[a] - 1) * 100 for a, b in zip(ms, ms[1:]) if zobs.shift(a, 1) == b][-12:]
        out["pace"] = (f"по данным рынка: {ms[-1]} — {ch[-1]:+.1f}% к прошлому месяцу; медиана за последние месяцы "
                       f"{statistics.median(ch):+.1f}% в месяц").replace(".", ",").replace("-", "−") if ch else ""
    p = S.get(PARK_ITEM.get(w, ""), {})
    if p:
        last = max(p)
        mm, yy = p.get(zobs.shift(last, -1)), p.get(zobs.shift(last, -12))
        txt = f"по данным рынка: парк на {last} — {round(p[last]):,} ваг.".replace(",", " ")
        if mm:
            txt += f", {(p[last] / mm - 1) * 100:+.1f}% за месяц".replace(".", ",").replace("-", "−")
        if yy:
            txt += f", {(p[last] / yy - 1) * 100:+.1f}% за год".replace(".", ",").replace("-", "−")
        out["park"] = out["pace_gon"] = out["balance"] = txt
    return out


def for_wagon(w, keys):
    """{ключ: {what, why, where, range, now}} для полей формы прогноза."""
    cur = now(w)
    out = {}
    for k in keys:
        hk = "pace_gon" if (k == "pace" and w in ("gon", "inno")) else k
        h = dict(HELP.get(hk, {}))
        if h:
            h["now"] = cur.get(hk, "")
            out[k] = h
    return out


