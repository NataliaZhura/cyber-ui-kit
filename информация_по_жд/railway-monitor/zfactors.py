def key(w):
    return "gon" if w in ("gon", "inno") else "kr" if w.startswith("kr") else "hop_grain" if w.startswith("hop") else "fit"


def md(w):
    L = ["| Группа | Фактор | Как влияет на ставку | Данные | В анализе | 2025–2026 гг. |", "|---|---|---|---|---|---|"]
    for g, f, how, src, st, note in BY[key(w)] + COMMON:
        L.append(f"| {g} | {f} | {how} | {src} | {st} | {note or '—'} |")
    L += ["", "<small>«+» — растёт показатель, растёт ставка; «−» — наоборот. «в базе» — ряд по месяцам участвует в разделах 1, "
          "3, 6; «открытые» — цифры из открытых источников (раздел 8); «нет» — данных пока нет, указано, где взять. Список "
          "пополняется: новый фактор — строка здесь, новый ряд — в базе наблюдений.</small>", ""]
    return L


