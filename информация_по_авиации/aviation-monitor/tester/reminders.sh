#!/usr/bin/env bash
# Мягкие вечерние напоминания тестовому пользователю: зайти в бота и попробовать то, что ещё не пробовал.
#   bash tester/reminders.sh <TELEGRAM_ID_тестировщика>
# Даты — на время теста (15 и 16.10.2026, 18:30 МСК); удаляются при отключении вместе с остальными «Тест: …».
set -euo pipefail
ID="${1:?Укажи Telegram ID тестировщика}"
[[ "$ID" =~ ^[0-9]{5,15}$ ]] || { echo "ID должен быть числом"; exit 1; }
MSG='Мягкое вечернее напоминание пользователю (он тестирует Ави, потенциальный клиент). Прочитай ~/aviation-monitor/saved_tester/activity.log — что он уже пробовал. Если сегодня запросов не было: 2–3 дружелюбные строки — Ави на связи, и ОДНА конкретная возможность, которую он ещё не пробовал, с готовым примером (например: /compare → Аэрофлот и ЮТэйр; «проверь демо-модель»; /finance → Победа; /market → за неделю). Если сегодня запросы были: одна строка благодарности и одна новая возможность. Без давления и восклицательных знаков, не длиннее 400 знаков, без списков.'
for d in 15 16; do
  n="Тест: напоминание $d.10"
  openclaw automations create "30 18 $d 10 *" "$MSG" --name "$n" --tz Europe/Moscow --agent tester \
    --session isolated --announce --channel telegram --to "$ID" | grep -E '"name"|"nextRunAtMs"' | head -2
done
